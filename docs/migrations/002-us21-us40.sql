on conflict(id) do update set public = false, file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;
drop policy if exists produk_upload_admin on storage.objects;
create policy produk_upload_admin on storage.objects for insert to authenticated with check (bucket_id = 'produk');
drop policy if exists produk_baca_admin on storage.objects;
create policy produk_baca_admin on storage.objects for select to authenticated using (bucket_id = 'produk');
drop policy if exists produk_hapus_admin on storage.objects;
create policy produk_hapus_admin on storage.objects for delete to authenticated using (bucket_id = 'produk');

notify pgrst, 'reload schema';
commit;
