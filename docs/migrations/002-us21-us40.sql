-- Jalankan seluruh berkas melalui Supabase SQL Editor sebelum deployment kode.
begin;

alter table public.produk add column if not exists aktif boolean not null default true;
create index if not exists produk_aktif_terbaru on public.produk(aktif, created_at desc, id desc);
create index if not exists produk_kategori_idx on public.produk(kategori);

create table if not exists public.kategori (
  nama text primary key check (length(btrim(nama)) between 1 and 100)
);
insert into public.kategori(nama)
select distinct kategori from public.produk where kategori is not null
on conflict do nothing;
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'produk_kategori_fkey' and conrelid = 'public.produk'::regclass) then
    alter table public.produk add constraint produk_kategori_fkey foreign key (kategori)
      references public.kategori(nama) on update cascade on delete restrict;
  end if;
end $$;

create table if not exists public.ulasan (
  id bigint generated by default as identity primary key,
  produk_id bigint not null references public.produk(id) on delete cascade,
  nama text not null check (length(btrim(nama)) between 2 and 80),
  rating integer not null check (rating between 1 and 5),
  komentar text not null check (length(btrim(komentar)) between 5 and 1000),
  terlihat boolean not null default true,
  created_at timestamptz not null default now()
);
create index if not exists ulasan_produk_waktu on public.ulasan(produk_id, created_at desc, id desc);
create table if not exists public.klik_whatsapp (
  id bigint generated by default as identity primary key,
  produk_id bigint not null references public.produk(id) on delete cascade,
  created_at timestamptz not null default now()
);
create index if not exists klik_whatsapp_produk on public.klik_whatsapp(produk_id);

alter table public.kategori enable row level security;
alter table public.ulasan enable row level security;
alter table public.klik_whatsapp enable row level security;
-- Aplikasi ini memiliki satu peran authenticated: pemilik/admin, sesuai schema.sql.
drop policy if exists kategori_admin on public.kategori;
create policy kategori_admin on public.kategori for all to authenticated using (true) with check (true);
drop policy if exists ulasan_admin on public.ulasan;
create policy ulasan_admin on public.ulasan for all to authenticated using (true) with check (true);
drop policy if exists klik_admin on public.klik_whatsapp;
create policy klik_admin on public.klik_whatsapp for select to authenticated using (true);
revoke all on public.kategori, public.ulasan, public.klik_whatsapp from public, anon;
revoke all on public.klik_whatsapp from authenticated;
grant select, insert, update, delete on public.kategori, public.ulasan to authenticated;
grant select on public.klik_whatsapp to authenticated;
grant all on public.kategori, public.ulasan, public.klik_whatsapp to service_role;
revoke all on sequence public.ulasan_id_seq, public.klik_whatsapp_id_seq from public, anon;
grant usage, select on sequence public.ulasan_id_seq to authenticated, service_role;
grant usage, select on sequence public.klik_whatsapp_id_seq to service_role;

-- SECURITY INVOKER: admin mengikuti RLS; RPC penulisan publik hanya service_role.
create or replace function public.statistik_produk()
returns table(kategori text, jumlah bigint) language sql stable security invoker set search_path = '' as $$
  select p.kategori, count(*) from public.produk p group by p.kategori;
$$;
revoke all on function public.statistik_produk() from public, anon;
grant execute on function public.statistik_produk() to authenticated, service_role;

create or replace function public.ringkasan_ulasan(p_produk_id bigint)
returns table(jumlah bigint, rata_rata numeric) language sql stable security invoker set search_path = '' as $$
  select count(*), coalesce(avg(u.rating), 0) from public.ulasan u
  join public.produk p on p.id = u.produk_id
  where p.id = p_produk_id and p.aktif and u.terlihat;
$$;
revoke all on function public.ringkasan_ulasan(bigint) from public, anon, authenticated;
grant execute on function public.ringkasan_ulasan(bigint) to service_role;

create or replace function public.kirim_ulasan(p_produk_id bigint, p_nama text, p_rating integer, p_komentar text)
returns bigint language plpgsql security invoker set search_path = '' as $$
declare hasil bigint;
begin
  if not exists (select 1 from public.produk where id = p_produk_id and aktif) then
    raise exception 'Produk tidak tersedia';
  end if;
  insert into public.ulasan(produk_id, nama, rating, komentar)
    values(p_produk_id, btrim(p_nama), p_rating, btrim(p_komentar)) returning id into hasil;
  return hasil;
end;
$$;
revoke all on function public.kirim_ulasan(bigint,text,integer,text) from public, anon, authenticated;
grant execute on function public.kirim_ulasan(bigint,text,integer,text) to service_role;

create or replace function public.catat_klik_whatsapp(p_ids bigint[])
returns void language plpgsql security invoker set search_path = '' as $$
begin
  if coalesce(array_length(p_ids, 1), 0) < 1 or array_length(p_ids, 1) > 20 then
    raise exception 'Daftar produk tidak valid';
  end if;
  insert into public.klik_whatsapp(produk_id)
    select distinct p.id from public.produk p where p.id = any(p_ids) and p.aktif;
end;
$$;
revoke all on function public.catat_klik_whatsapp(bigint[]) from public, anon, authenticated;
grant execute on function public.catat_klik_whatsapp(bigint[]) to service_role;

